def gradeConverter(mark):
    
    if mark>=90:
        print('A+')

    elif mark>=85:
        print('A')    

    elif mark>=80:
        print('B+')

    elif mark>=75:
        print('B')

    elif mark>=70:
        print('C+')

    elif mark>=65:
        print('c')

    elif mark>=60:
        print('D+')

    elif mark>=50:
        print('D')                    

    else:
        print('F')

    

gradeConverter(30)